const CITY_ORDER = ["delhi", "mumbai", "bengaluru", "goa"];

export function listCities(): { id: string; name: string }[] {
  const ids = new Set<string>();
  for (const hotel of CATALOG) ids.add(canonicalCity(hotel.city));
  return [...ids].sort((left, right) => {
    const leftRank = CITY_ORDER.indexOf(left);
    const rightRank = CITY_ORDER.indexOf(right);
    if (leftRank === -1 && rightRank === -1) return left.localeCompare(right);
    if (leftRank === -1) return 1;
    if (rightRank === -1) return -1;
    return leftRank - rightRank;
  }).map((id) => ({ id, name: displayCity(id) }));
}

export function providerStats(): { id: ProviderId; name: string; hotels: number }[] {
  return (Object.keys(PROVIDERS) as ProviderId[]).map((id) => ({
    id,
    name: PROVIDERS[id],
    hotels: CATALOG.filter((hotel) => hotel.provider === id).length,
  }));
}
